// 問題は親の筋と共有する。手がかり・行動・決着・余韻はルート単位で選び、混線させない。
// 配列は 助言・行動・決着・自分の発見・仲間の発見・寄り道・余韻・その後。
function route(id, label, outcome, kids, adult) {
  const result = { id, label, outcome, variation: {} };
  for (const [audience, texts] of Object.entries({ kids, adult })) {
    if (texts.length !== 8) throw new Error('Invalid route: ' + id);
    result[audience] = Object.fromEntries(['clue', 'action', 'resolution'].map((key, i) => [key, [texts[i]]]));
    result.variation[audience] = Object.fromEntries(['self', 'companion', 'beat', 'echo', 'after'].map((key, i) => [key, texts[i + 3]]));
  }
  return result;
}

