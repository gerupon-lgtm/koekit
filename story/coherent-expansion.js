// 追加の20筋。各段階をひとまとまりで定義し、別の筋の解決を混ぜない。
// 配列は 問題・助言・行動・決着・自分の発見・仲間の発見・寄り道・余韻・その後。
export function definePlot(id, label, outcome, kids, adult) {
  const plot = { id, label, outcome, variation: {} };
  for (const [audience, texts] of Object.entries({ kids, adult })) {
    if (texts.length !== 9) throw new Error('Invalid plot: ' + id);
    plot[audience] = Object.fromEntries(['problem', 'clue', 'action', 'resolution'].map((key, i) => [key, [texts[i]]]));
    plot.variation[audience] = Object.fromEntries(['self', 'companion', 'beat', 'echo', 'after'].map((key, i) => [key, texts[i + 4]]));
  }
  return plot;
}

