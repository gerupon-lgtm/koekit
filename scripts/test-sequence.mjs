import assert from 'node:assert/strict';
import { SequenceAnswer, sequenceLevels, makeSequence, SEQUENCE_SETTINGS } from '../src/game/sequence.js';
import { Judge } from '../src/game/judge.js';
import { SequencePhase, SEQUENCE_PHASES as SP } from '../src/game/sequence-phase.js';
import { PHASES } from '../src/game/phase.js';
const levels=sequenceLevels();
assert.equal(levels.length,10);
assert.equal(levels[0].steps,2); assert.equal(levels[4].steps,6);
assert.equal(levels[5].onMs,600); assert.equal(levels[0].offMs,400);
assert.equal(sequenceLevels({...SEQUENCE_SETTINGS,maxSteps:9}).length,16);
assert.deepEqual(makeSequence(3,()=>0),['up','up','up']);
const a=new SequenceAnswer(['right','up','right']);
assert.equal(a.submit(),null);
a.add('right'); a.add('up'); a.add('right'); a.add('left');
assert.deepEqual(a.values,['right','up','right']);
assert.equal(a.ready,true);
a.undo(); assert.equal(a.ready,false);
a.add('right'); assert.equal(a.submit(),true);
assert.equal(a.submit(),null,'score once');
a.undo(); assert.deepEqual(a.values,['right','up','right']);
const b=new SequenceAnswer(['left','left']);b.add('right'); b.clear();
assert.deepEqual(b.target,['left','left']); assert.deepEqual(b.values,[]);
b.add('left');b.add('right');assert.equal(b.submit(),false);
const j=new Judge({maxAttempts:3,clearHits:2});
assert.equal(j.record('wrong'),'playing');assert.equal(j.record('wrong'),'playing');assert.equal(j.record('correct'),'gameover');
const phase=new SequencePhase({startListening(){},stopListening(){}});
phase.setLevelVocab(['up','right']);phase.to(SP.ANSWER);
assert.equal(phase.handleRaw('オッケー'),'');
assert.equal(phase.handleRaw('もどす'),'undo');assert.equal(phase.handleRaw('やりなおし'),'clearAnswer');
phase.to(SP.CONFIRM);assert.equal(phase.handleRaw('みぎ'),'');assert.equal(phase.handleRaw('オッケー'),'confirm');
phase.to(PHASES.RESULT);assert.equal(phase.handleRaw('もどす'),'');
console.log('sequence: passed');
