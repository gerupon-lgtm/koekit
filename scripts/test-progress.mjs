import assert from 'node:assert/strict';
import { Progress } from '../src/game/progress.js';
const data = new Map();
const storage = { getItem: k => data.get(k) ?? null, setItem: (k,v) => data.set(k,v) };
const p = new Progress('doubutsu', { storage });
assert.equal(p.highest(), null);
p.clear('5');
assert.equal(p.unlocked(), false, 'last level alone must not unlock');
assert.equal(p.highest().name, 'ぜんほうこうマスター');
p.clear('1');
assert.equal(p.highest().rank, 5, 'never demote');
assert.equal(p.clear('extra'), null, 'locked speed cannot be recorded');
for (const id of ['2','3','4']) p.clear(id);
assert.equal(p.unlocked(), true);
p.clear('extra');
assert.equal(p.highest().name, 'スピードマスター');
assert.equal(new Progress('doubutsu', { storage }).highest().rank, 100);
assert.equal(new Progress('kioku-place', { storage }).highest(), null);
p.clear('0'); p.clear('bogus');
assert.equal(p.completed('0'), false);
const broken = { getItem: () => '{', setItem() { throw Error('blocked'); } };
const q = new Progress('kioku-place', { storage: broken });
assert.equal(q.highest(), null);
q.clear('1'); assert.equal(q.highest().rank, 1); assert.equal(q.persistent, false);
const seq = new Progress('kioku-sequence', { storage, maxLevel: 5, speedIds: ['s1','s2','s3','s4','s5'] });
for (let i=1;i<=5;i++) seq.clear(String(i));
assert.equal(seq.highest().name, '6てマスター');
seq.clear('s5'); assert.equal(seq.highest().rank, 5);
for (let i=1;i<=4;i++) seq.clear('s'+i);
assert.equal(seq.highest().rank, 100);
console.log('progress: passed');
